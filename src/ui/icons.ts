export type IconName = keyof typeof ICONS

export const ICON_COLORS: Record<string, string> = { '#': 'currentColor', a: 'var(--icon-a, #d9a84a)', b: 'var(--icon-b, #d9573c)', c: 'var(--icon-c, #f3ead7)' }

/** Прямоугольники значка: соседние клетки одного цвета в строке - одним прямоугольником. */
export function iconRects(name: IconName): { x: number; y: number; w: number; fill: string }[] {
  const out: { x: number; y: number; w: number; fill: string }[] = []
  ICONS[name].forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      let w = 1
      while (row[x + w] === ch) w++
      if (ch !== '.' && ICON_COLORS[ch]) out.push({ x, y, w, fill: ICON_COLORS[ch] })
      x += w
    }
  })
  return out
}

export function iconSize(name: IconName): [number, number] {
  const map = ICONS[name]
  return [Math.max(...map.map((r) => r.length)), map.length]
}
